"use client"

import { useSyncExternalStore } from "react"
import { useAuth } from "@/context/AuthContext"

export type Language = "en" | "ur"

/** UI language from user profile (Manage profile). When user selects Urdu, dashboard and diagnostic tests use this. */
export function useProfileLanguage(): Language {
  const { user } = useAuth()
  const raw = (user as { lang_pref?: string } | undefined)?.lang_pref
  if (!raw) return "en"
  const s = String(raw).toLowerCase().trim()
  return s === "ur" || s === "urdu" ? "ur" : "en"
}

/** Dict for current profile language (for dashboard + diagnostic tests). */
export function useProfileDict() {
  const lang = useProfileLanguage()
  return dict[lang]
}

// tiny external store for language with localStorage persistence
let currentLang: Language = "en"
const listeners = new Set<() => void>()

function readPersisted(): Language | null {
  if (typeof window === "undefined") return null
  const v = window.localStorage.getItem("mindease_lang")
  return v === "en" || v === "ur" ? v : null
}

if (typeof window !== "undefined") {
  const persisted = readPersisted()
  if (persisted) currentLang = persisted
}

export function setLanguage(lang: Language) {
  currentLang = lang
  if (typeof window !== "undefined") {
    window.localStorage.setItem("mindease_lang", lang)
  }
  listeners.forEach((l) => l())
}

export function getLanguage(): Language {
  return currentLang
}

export function subscribe(cb: () => void) {
  listeners.add(cb)
  return () => listeners.delete(cb)
}

export function useLanguage(): Language {
  return useSyncExternalStore(subscribe, getLanguage, getLanguage)
}

